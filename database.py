
import os
import sqlite3
from contextlib import closing, contextmanager

import psycopg
from psycopg.rows import dict_row


DATABASE_URL = os.getenv("DATABASE_URL")
DB_NAME = os.getenv("PULSECHECK_DB", "pulsecheck.db")


def _is_sqlite(db_name=None):
    return db_name is not None or not DATABASE_URL


@contextmanager
def _connection(db_name=None):
    if _is_sqlite(db_name):
        with closing(sqlite3.connect(db_name or DB_NAME)) as conn:
            conn.row_factory = sqlite3.Row
            with conn:
                yield conn
    else:
        with psycopg.connect(DATABASE_URL, row_factory=dict_row) as conn:
            yield conn


@contextmanager
def _cursor(conn):
    cur = conn.cursor()
    try:
        yield cur
    finally:
        cur.close()


def _sql(query, db_name=None):
    if _is_sqlite(db_name):
        return query.replace("%s", "?")
    return query


def init_db(db_name=None):
    with _connection(db_name) as conn:
        if _is_sqlite(db_name):
            conn.executescript("""
                CREATE TABLE IF NOT EXISTS checks (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    url TEXT NOT NULL,
                    status_code INTEGER,
                    is_up BOOLEAN NOT NULL,
                    response_time_ms REAL,
                    checked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                );

                CREATE TABLE IF NOT EXISTS monitored_sites (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    url TEXT NOT NULL UNIQUE,
                    interval_minutes INTEGER NOT NULL DEFAULT 5,
                    is_enabled BOOLEAN NOT NULL DEFAULT 1,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    last_checked_at TIMESTAMP
                );
            """)
        else:
            with _cursor(conn) as cur:
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS checks (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        url TEXT NOT NULL,
                        status_code INTEGER,
                        is_up BOOLEAN NOT NULL,
                        response_time_ms DOUBLE PRECISION,
                        checked_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
                    )
                """)
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS monitored_sites (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        url TEXT NOT NULL UNIQUE,
                        interval_minutes INTEGER NOT NULL DEFAULT 5,
                        is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
                        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                        last_checked_at TIMESTAMPTZ
                    )
                """)


def save_check(
    url,
    status_code,
    is_up,
    response_time_ms,
    db_name=None,
):
    with _connection(db_name) as conn:
        with _cursor(conn) as cur:
            cur.execute(
                _sql("""
                    INSERT INTO checks
                    (url, status_code, is_up, response_time_ms)
                    VALUES (%s, %s, %s, %s)
                """, db_name),
                (url, status_code, bool(is_up), response_time_ms),
            )


def get_history(limit=20, db_name=None):
    with _connection(db_name) as conn:
        with _cursor(conn) as cur:
            cur.execute(
                _sql("""
                    SELECT * FROM checks
                    ORDER BY id DESC
                    LIMIT %s
                """, db_name),
                (limit,),
            )
            rows = cur.fetchall()

        return [dict(row) for row in rows]


def add_monitored_site(url, interval_minutes=5, db_name=None):
    with _connection(db_name) as conn:
        with _cursor(conn) as cur:
            cur.execute(
                _sql("""
                    INSERT INTO monitored_sites (url, interval_minutes)
                    VALUES (%s, %s)
                    RETURNING id
                """, db_name),
                (url, interval_minutes),
            )
            row = cur.fetchone()
            return row["id"] if isinstance(row, dict) else row[0]


def get_monitored_sites(db_name=None):
    with _connection(db_name) as conn:
        with _cursor(conn) as cur:
            cur.execute(
                "SELECT * FROM monitored_sites ORDER BY id DESC"
            )
            rows = cur.fetchall()

        return [dict(row) for row in rows]


def remove_monitored_site(site_id, db_name=None):
    with _connection(db_name) as conn:
        with _cursor(conn) as cur:
            cur.execute(
                _sql(
                    "DELETE FROM monitored_sites WHERE id = %s",
                    db_name,
                ),
                (site_id,),
            )
            return cur.rowcount > 0


def update_monitored_site_last_checked(site_id, db_name=None):
    with _connection(db_name) as conn:
        with _cursor(conn) as cur:
            cur.execute(
                _sql("""
                    UPDATE monitored_sites
                    SET last_checked_at = CURRENT_TIMESTAMP
                    WHERE id = %s
                """, db_name),
                (site_id,),
            )
            return cur.rowcount > 0
